package claude

import (
	"strings"

	"github.com/zigai/aht/v2/internal/harness/transcript"
)

const localCommandCaveat = "Caveat: The messages below were generated by the user while running local commands"

func userPromptParts(body string) []transcript.TextPart {
	return transcript.UserParts(splitUserPrompt(body))
}

func splitUserPrompt(body string) (string, string) {
	body = strings.TrimSpace(body)

	text := body
	if strings.HasPrefix(text, localCommandCaveat) {
		return body, ""
	}

	var command, arguments string

	for {
		name, content, rest, ok := transcript.LeadingBlock(text)
		if !ok {
			break
		}

		switch name {
		case "command-name":
			command = strings.TrimSpace(content)
		case "command-args":
			arguments = strings.TrimSpace(content)
		}

		text = strings.TrimSpace(rest)
	}

	injected := strings.TrimSpace(body[:len(body)-len(text)])
	if text == "" && command != "" {
		text = strings.TrimSpace(command + " " + arguments)
	}

	return injected, text
}
